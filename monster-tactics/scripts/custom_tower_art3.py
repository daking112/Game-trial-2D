# coiled salamander (no other line drops the shared stub-leg base), a
# teardrop tadpole tapering to a single tail-fin, a flower-sprite ringed by
# a petal crown, a round-eared mouse with a zigzag lightning tail, a
# square-jawed rock pup with floppy stone ears, and a legless ghost with a
# wavy hem instead of feet. Same conventions as every other line: compact
# body in a clear margin, oversized 2px eyes with the pupil directly
# beneath, flat 2-3 tone fills with the darker shade low, 1px near-black
# outline, and each stage visibly larger/more ornamented than the last.

