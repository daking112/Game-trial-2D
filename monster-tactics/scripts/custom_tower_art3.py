# Third batch of hand-authored tower monsters - see custom_tower_art.py for
# the full style notes and the grid/palette format (reused verbatim here,
# same as custom_tower_art2.py).
#
# Batches one and two each filled empty or thin cells of the type/rarity
# gacha table; by the time this batch was written every cell already had at
# least one catchable species, so this batch instead rounds out the
# thinnest remaining cell of each type (one more per type: FIRE/COMMON,
# WATER/COMMON, GRASS/RARE, ELECTRIC/COMMON, EARTH/RARE, NORMAL/EPIC) so
# every type has real pull variety at more than one rarity, not just a
# bigger total count.
#
